"""Generates programs/sharded-amm/src/math/tick_table.rs.

Entry i is sqrt(1.0001^(2^i)) as a normalized binary float: a mantissa
M_i in [2^127, 2^128) and an exponent E_i with value ~= M_i * 2^E_i, where
M_i = floor(value * 2^-E_i) is computed exactly with integer square roots
(no floating point). CI regenerates the file and fails if it differs from
the committed copy.

Usage: python3 -I tools/reference/tick_table.py > programs/sharded-amm/src/math/tick_table.rs
"""
from math import isqrt

BITS = 19  # 2^18 <= MAX_TICK = 443636 < 2^19


def entry(i: int):
    n = 1 << i
    num, den = 10001**n, 10000**n
    # floor(log2(sqrt(num/den))) via the integer part of num/den.
    log2 = ((num // den).bit_length() - 1) // 2
    k = 127 - log2
    m = isqrt((num << (2 * k)) // den)
    while m >= 1 << 128:  # guard against the floor(log2) estimate being low
        k -= 1
        m = isqrt((num << (2 * k)) // den)
    while m < 1 << 127:
        k += 1
        m = isqrt((num << (2 * k)) // den)
    return m, -k


def main() -> None:
    print("// @generated by tools/reference/tick_table.py. Do not edit by hand.")
    print("//")
    print("// SQRT_POW[i] = (M, E) with sqrt(1.0001^(2^i)) ~= M * 2^E,")
    print("// M = floor(sqrt(1.0001^(2^i)) * 2^-E) in [2^127, 2^128), exact integer square root.")
    print()
    print(f"pub const SQRT_POW_BITS: usize = {BITS};")
    print()
    print("#[rustfmt::skip]")
    print("pub const SQRT_POW: [(u128, i32); SQRT_POW_BITS] = [")
    for i in range(BITS):
        m, e = entry(i)
        print(f"    (0x{m:032x}, {e}),")
    print("];")


if __name__ == "__main__":
    main()
