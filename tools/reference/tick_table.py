#!/usr/bin/env python3
"""Generates programs/sharded-amm/src/math/tick_table.rs.

Entry i of SQRT_POW is sqrt(1.0001^(2^i)), and of SQRT_POW_NEG
sqrt(1.0001^-(2^i)), each as a normalized binary float: a mantissa
M_i in [2^127, 2^128) and an exponent E_i with value ~= M_i * 2^E_i, where
M_i = floor(value * 2^-E_i) is computed exactly with integer square roots
(no floating point). CI regenerates the file and fails if it differs from
the committed copy.

Usage: python3 -I tools/reference/tick_table.py > programs/sharded-amm/src/math/tick_table.rs
"""
from math import isqrt

BITS = 19  # 2^18 <= MAX_TICK = 443636 < 2^19


def entry(i: int, negative: bool):
    n = 1 << i
    num, den = 10001**n, 10000**n
    if negative:
        num, den = den, num
    # floor(log2(sqrt(num/den))), possibly off by one; the loops correct it.
    log2 = (num.bit_length() - den.bit_length()) // 2
    k = 127 - log2
    m = isqrt((num << (2 * k)) // den) if k >= 0 else isqrt(num // (den << (-2 * k)))
    while m >= 1 << 128:
        k -= 1
        m = isqrt((num << (2 * k)) // den)
    while m < 1 << 127:
        k += 1
        m = isqrt((num << (2 * k)) // den)
    return m, -k


def main() -> None:
    print("// @generated by tools/reference/tick_table.py. Do not edit by hand.")
    print("//")
    print("// SQRT_POW[i] = (M, E) with sqrt(1.0001^(2^i)) ~= M * 2^E and SQRT_POW_NEG[i]")
    print("// the same for sqrt(1.0001^-(2^i)); M = floor(value * 2^-E) in [2^127, 2^128),")
    print("// computed with exact integer square roots.")
    print()
    print(f"pub const SQRT_POW_BITS: usize = {BITS};")
    print()
    for name, negative, sign in (("SQRT_POW", False, ""), ("SQRT_POW_NEG", True, "-")):
        print(f"/// sqrt(1.0001^{sign}(2^i)) as (mantissa, exponent).")
        print("#[rustfmt::skip]")
        print(f"pub const {name}: [(u128, i32); SQRT_POW_BITS] = [")
        for i in range(BITS):
            m, e = entry(i, negative)
            print(f"    (0x{m:032x}, {e}),")
        print("];")
        if not negative:
            print()

if __name__ == "__main__":
    main()
