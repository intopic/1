#!/usr/bin/env python3
"""Generates programs/sharded-amm/src/math/tick_table.rs.

Each entry is floor(2^128 * sqrt(1.0001^(2^i))) computed exactly with integer
square roots (no floating point, no rounding in between), so the table does
not depend on any other implementation. CI regenerates the file and fails if
it differs from the committed copy.

Usage: python3 -I tools/reference/tick_table.py > programs/sharded-amm/src/math/tick_table.rs
"""
from math import isqrt

BITS = 19  # 2^18 <= MAX_TICK = 443636 < 2^19


def entry(i: int) -> int:
    n = 1 << i
    return isqrt((10001**n << 256) // 10000**n)


def limbs(v: int) -> str:
    assert v < 1 << 256
    return ", ".join(f"0x{(v >> (64 * k)) & (2**64 - 1):016x}" for k in range(4))


def main() -> None:
    print("// @generated by tools/reference/tick_table.py. Do not edit by hand.")
    print("//")
    print("// SQRT_POW[i] = floor(2^128 * sqrt(1.0001^(2^i))), exact integer square root.")
    print("// Limbs are little-endian u64 words of a U256.")
    print("use super::wide::U256;")
    print()
    print(f"pub const SQRT_POW_BITS: usize = {BITS};")
    print()
    print("#[rustfmt::skip]")
    print(f"pub const SQRT_POW: [U256; SQRT_POW_BITS] = [")
    for i in range(BITS):
        print(f"    U256([{limbs(entry(i))}]),")
    print("];")


if __name__ == "__main__":
    main()
